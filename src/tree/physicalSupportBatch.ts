type Suggestion = SkillPreferencePreset["suggestions"][number];
type Override = { summary: string; priorities?: readonly Suggestion[] };
const suggestion = (id: PassivePreferenceId, reason: string, weight = 2): Suggestion => ({ id, reason, weight });
const bleedingIds = ["bleedingChance","bleedingMagnitude","bleedingDuration"] as const;

function priorities(id: string): Suggestion[] {
  if (id === "excise") return [
    suggestion("criticalChance","Optional critical chance for eligible hits, not a Full DPS benefit or an answer to the added cooldown."),
    suggestion("cooldownRecoveryRate","Recovery of the support's actual cooldown, not bypassing it or guaranteeing cast/attack throughput."),
  ];
  if (id === "rending-apex") return [suggestion("armourBreakAmount","Strength of actual Final-Strike Armour Break, not granting a Final Strike, full break or a damage multiplier.")];
  if (id === "knockback") return [suggestion("knockbackDistance","Distance of eligible Knockbacks, not guaranteed movement or direct damage.")];
  if (id === "overreach") return [
    suggestion("areaOfEffect","Coverage of the reviewed area component, not extra hit damage or guaranteed overlap."),
    suggestion("accuracy","Optional source Accuracy does not cancel Overreach's multiplicative close-range penalty or guarantee contact."),
  ];
  if (id.startsWith("enduring-impact-")) return [suggestion("stunBuildup","Own Heavy Stun is required for charge events; no charge uptime is supplied.",1)];
  if (id === "opening-move") return [suggestion("dazeDuration","Duration of an actual opening Daze against Full-Life enemies, not application on every hit.",1)];
  return [];
}

export const physicalSkillSupports: readonly ReviewedSkillSupport[] = reviews.map(review => {
  const ids: readonly PassivePreferenceId[] = review.id === "bleed-iv" || review.id === "haemocrystals"
    ? bleedingIds : review.id === "bone-shrapnel" ? ["pinBuildup"]
    : review.family === "Pursuit" ? ["projectileDamage"] : [];
  return {
    id:review.id,name:review.name,effectId:review.effectId,family:review.family,
    skillIds:scopes[review.group],summary:review.summary,sourceUrl:review.sourceUrl,priorities:priorities(review.id),
    ...(ids.length ? {exclusions:ids.map(id=>({id,reason:"A selected support prohibits this supported component. Suggestions cannot bypass it; manual weights remain available for review and other skills."}))} : {}),
    ...(review.family === "Retreat" ? {disabledPassiveStatScopes:["meleeDamage" as const]} : {}),
  };
});

export function physicalSupportOverride(support: ReviewedSkillSupport, selected: readonly string[]): Override | undefined {
  const has = (id:string) => selected.includes(id);
  const family = (prefix:string) => selected.some(id=>id.startsWith(prefix));
  const noBleed = has("bleed-iv") || has("haemocrystals");
  const noPin = has("bone-shrapnel"), noStun = family("pin-");
  const noCrit = has("controlled-destruction"), brutality = family("brutality-");
  const retreat = family("retreat-"), pursuit = family("pursuit-");
  const messages:string[] = [];
  let nextPriorities = support.priorities, changed = false;
  const block = (message:string) => { messages.push(message); nextPriorities=[]; changed=true; };

  if (noBleed && support.family === "Bleed" && support.id !== "bleed-iv" && has("malady"))
    messages.push("Bleeding is still prohibited. Malady's swapped on-hit Poison chance is separate and does not restore Bleeding; neither event nor enemy-condition uptime is supplied.");
  else if (noBleed && ["Incision","DeepCuts","Bleed"].includes(support.family) && support.id !== "bleed-iv")
    block("Selected supports prevent this skill from inflicting Bleeding. Incision or magnitude cannot bypass the prohibition or supply its own consumption event; external Bleeding remains separate from this skill's own Bleeding.");
  if (noBleed && ["Rupture","RustedSpikes"].includes(support.family))
    messages.push("Existing Bleeding must come from another eligible source. A Bleeding prohibition does not erase external Bleeding, but does not establish an aggravation event or uptime either.");
  if (noPin && (support.family === "Pin" || support.id === "rusted-spikes"))
    block("Bone Shrapnel prevents this skill's Pin buildup. Pin support does not bypass that restriction and still prevents Stun; do not credit self-supplied Pin, Heavy Stun or its Pin-event rewards.");
  if (noStun && support.family === "EnduringImpact")
    block("Pin prevents this skill from Stunning. An externally Heavy-Stunned target is not this skill causing Heavy Stun and cannot supply Enduring Impact's charge event.");
  if (noStun && support.id === "retaliate-ii")
    messages.push("Pin prevents outgoing Stun despite Tier II's buildup benefit. The player-Stun-Bar damage condition is separate and is not automatically disabled or supplied.");
  if (has("excise") && noCrit && support.id === "excise") {
    messages.push("Controlled Destruction prevents critical hits, so Excise cannot supply its crit benefit. Its cooldown still applies; only optional cooldown-recovery priority remains.");
    nextPriorities=support.priorities.filter(p=>p.id!=="criticalChance"); changed=true;
  }
  if (has("hit-and-run") && (has("excise") || has("nova-projectiles-ii") || family("combo-finisher-"))
    && (support.id==="hit-and-run" || support.id==="excise" || support.family==="NovaProjectiles" || support.family==="ComboFinisher"))
    block("Hit and Run conflicts with a selected added cooldown or use condition. Native links can be ignored; selections are retained for review, not counted as a valid combined loadout or usable attack sequence.");
  if (has("crater") && has("tectonic-slams") && (support.id==="crater" || support.id==="tectonic-slams"))
    block("Crater adds Fissure behavior, which makes Tectonic Slams ineligible in reviewed PoB. Do not combine its Aftershock bonuses, penalties or costs as though both links applied.");
  if (retreat && pursuit && (support.family==="Retreat" || support.family==="Pursuit"))
    block("Retreat and Pursuit disable this skill's Melee and Projectile damage respectively. Do not count the same hit as both alternation triggers or assume the bonuses compensate these prohibitions.");
  if (pursuit && support.family==="ProjectileSpeed")
    messages.push("Pursuit disables this skill's Projectile damage. Delivery speed is not a restored damaging Projectile component; manual preferences remain for review.");
  if (brutality && support.family==="ChargedShots")
    messages.push("Brutality prohibits the gained Lightning damage. Tier I's conditional Mana recovery and both tiers' costs remain separate; no refund cadence or sustain is assumed.");
  if (has("embitter") && support.family==="ChargedShots")
    messages.push("Embitter redirects the conditional gained damage to Cold, not base damage. It does not remove the third-shot requirement or costs; Brutality still prohibits the redirected Element.");
  if (brutality && support.id==="volcanic-eruption")
    messages.push("The separate Eruption is Fire damage; Brutality prohibits linked Elemental damage. External Ignite eligibility is not permission to bypass that damage prohibition or assume child damage.");
  if (support.id==="gambleshot" && (has("fork") || family("pierce-") || family("chain-")))
    messages.push("Other delivery supports do not guarantee the random outcome or extra contacts. Collision priority and eligibility still apply; do not count a contact as Piercing, Forking and Chaining at once.");
  if (has("rage-iii") && family("rageforged-") && (support.family==="Rage" || support.family==="RageForged"))
    messages.push("Rage generation and ten-Rage spending are separate events. Five Rage per eligible hit does not prove a sustainable use rate; Tier III speed requires being below maximum, not simultaneous maximum-Rage uptime.");
  return messages.length || changed ? {summary:messages.join(" "),...(changed?{priorities:nextPriorities}:{})} : undefined;
}
